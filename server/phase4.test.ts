// ─── Custom Swarms Router ─────────────────────────────────────────────────────

describe("custom swarms router", () => {
  it("swarms router file exports swarmsRouter", async () => {
    const mod = await import("./routers/swarms");
    expect(mod.swarmsRouter).toBeDefined();
    expect(typeof mod.swarmsRouter).toBe("object");
  });

  it("swarmsRouter has all required procedures", async () => {
    const { swarmsRouter } = await import("./routers/swarms");
    const router = swarmsRouter as unknown as { _def: { procedures: Record<string, unknown> } };
    const procedures = router._def?.procedures ?? {};
    const procedureNames = Object.keys(procedures);
    expect(procedureNames).toContain("list");
    expect(procedureNames).toContain("get");
    expect(procedureNames).toContain("create");
    expect(procedureNames).toContain("update");
    expect(procedureNames).toContain("delete");
  });

  it("swarmsRouter is wired into the main appRouter", async () => {
    const { appRouter } = await import("./routers");
    const router = appRouter as unknown as { _def: { procedures: Record<string, unknown> } };
    const procedures = router._def?.procedures ?? {};
    // tRPC flattens sub-routers as "swarms.list", "swarms.create", etc.
    const hasSwarms = Object.keys(procedures).some((k) => k.startsWith("swarms."));
    expect(hasSwarms).toBe(true);
  });
});

