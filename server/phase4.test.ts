// ─── Export Document Format ───────────────────────────────────────────────────

describe("swarm export document format", () => {
  // Replicate the buildCustomExportDocument logic to test it independently
  function buildCustomExportDocument(
    name: string,
    goal: string,
    topology: string,
    agents: Array<{
      id: string;
      name: string;
      role: string;
      systemPrompt: string;
      inputFrom: string;
      outputTo: string;
      handoffCondition: string;
      sourceExampleTitle?: string;
    }>
  ): string {
    const lines: string[] = [
      `# ${name}`,
      ``,
      `**Goal:** ${goal || "Not specified"}`,
      `**Topology:** ${topology}`,
      `**Agents:** ${agents.length}`,
      `**Built with:** Promptwright — by ASSESS LLC`,
      ``,
      `---`,
      ``,
    ];
    agents.forEach((agent, idx) => {
      lines.push(`### Agent ${idx + 1}: ${agent.name}`);
      lines.push(``);
      lines.push(`**Role:** ${agent.role}`);
      if (agent.inputFrom) lines.push(`**Receives input from:** ${agent.inputFrom}`);
      if (agent.outputTo) lines.push(`**Sends output to:** ${agent.outputTo}`);
      if (agent.handoffCondition) lines.push(`**Handoff condition:** ${agent.handoffCondition}`);
      if (agent.sourceExampleTitle) {
        lines.push(`**System prompt source:** Example Library — "${agent.sourceExampleTitle}"`);
      }
      lines.push(``);
      lines.push(`**System Prompt:**`);
      lines.push(``);
      lines.push("```");
      lines.push(agent.systemPrompt);
      lines.push("```");
      lines.push(``);
      lines.push(`---`);
      lines.push(``);
    });
    lines.push(`*Generated by Promptwright — by ASSESS LLC*`);
    return lines.join("\n");
  }

  const testAgents = [
    {
      id: "agent_1",
      name: "Research Lead",
      role: "Researches market trends",
      systemPrompt: "You are a research specialist. Your job is to gather and synthesize market data.",
      inputFrom: "user",
      outputTo: "Content Writer",
      handoffCondition: "When research is complete",
    },
    {
      id: "agent_2",
      name: "Content Writer",
      role: "Writes content based on research",
      systemPrompt: "You are a content writer. Your job is to turn research into compelling copy.",
      inputFrom: "Research Lead",
      outputTo: "user",
      handoffCondition: "When draft is complete",
      sourceExampleTitle: "SEO-Optimized Blog Post",
    },
  ];

  it("export document contains the swarm name as H1", () => {
    const doc = buildCustomExportDocument("ASSESS Business Swarm", "Run weekly business review", "sequential", testAgents);
    expect(doc).toContain("# ASSESS Business Swarm");
  });

  it("export document contains ASSESS LLC branding", () => {
    const doc = buildCustomExportDocument("Test Swarm", "Test goal", "sequential", testAgents);
    expect(doc).toContain("ASSESS LLC");
    expect(doc).toContain("Promptwright — by ASSESS LLC");
  });

  it("export document contains all agent names", () => {
    const doc = buildCustomExportDocument("Test Swarm", "Test goal", "sequential", testAgents);
    expect(doc).toContain("### Agent 1: Research Lead");
    expect(doc).toContain("### Agent 2: Content Writer");
  });

  it("export document contains agent system prompts in code blocks", () => {
    const doc = buildCustomExportDocument("Test Swarm", "Test goal", "sequential", testAgents);
    expect(doc).toContain("```\nYou are a research specialist.");
    expect(doc).toContain("```\nYou are a content writer.");
  });

  it("export document shows source example provenance when present", () => {
    const doc = buildCustomExportDocument("Test Swarm", "Test goal", "sequential", testAgents);
    expect(doc).toContain('System prompt source:** Example Library — "SEO-Optimized Blog Post"');
  });

  it("export document shows handoff conditions", () => {
    const doc = buildCustomExportDocument("Test Swarm", "Test goal", "sequential", testAgents);
    expect(doc).toContain("**Handoff condition:** When research is complete");
    expect(doc).toContain("**Handoff condition:** When draft is complete");
  });

  it("export document shows routing (inputFrom / outputTo)", () => {
    const doc = buildCustomExportDocument("Test Swarm", "Test goal", "sequential", testAgents);
    expect(doc).toContain("**Receives input from:** user");
    expect(doc).toContain("**Sends output to:** Content Writer");
  });

  it("export document ends with Promptwright attribution", () => {
    const doc = buildCustomExportDocument("Test Swarm", "Test goal", "sequential", testAgents);
    expect(doc.trim().endsWith("*Generated by Promptwright — by ASSESS LLC*")).toBe(true);
  });
});

// ─── Seed Data Bug Fix ────────────────────────────────────────────────────────

describe("swarm seed data correctness", () => {
  it("seed file does not contain marketing_lead routing to finance_lead (bug fix)", async () => {
    const fs = await import("fs");
    const path = await import("path");
    const seedPath = path.join(process.cwd(), "scripts", "seed-swarm-templates.mjs");
    const content = fs.readFileSync(seedPath, "utf-8");
    // The bug was marketing_lead outputTo: "finance_lead" — should be "orchestrator"
    expect(content).not.toContain('"marketing_lead" → finance_lead');
    // Verify the fix: marketing_lead should route to orchestrator
    const marketingLeadSection = content.match(/marketing_lead[\s\S]{0,500}outputTo/);
    if (marketingLeadSection) {
      expect(marketingLeadSection[0]).not.toContain("finance_lead");
    }
  });

  it("seed file defines 8 swarm templates", async () => {
    const fs = await import("fs");
    const path = await import("path");
    const seedPath = path.join(process.cwd(), "scripts", "seed-swarm-templates.mjs");
    const content = fs.readFileSync(seedPath, "utf-8");
    // Count slug: occurrences as a proxy for template count
    const slugMatches = content.match(/slug:/g);
    expect(slugMatches).not.toBeNull();
    // There should be at least 8 slug: entries (one per template)
    expect(slugMatches!.length).toBeGreaterThanOrEqual(8);
  });
});

